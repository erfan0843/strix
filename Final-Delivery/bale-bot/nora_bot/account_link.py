"""
ورود به صفحهٔ پیوند حساب از داخل بله — پل میان سایت و مینی‌اپ.

پیوند حساب با اثبات مالکیت انجام می‌شود و آن اثبات یک امضای یک‌بارمصرفِ بله است
که فقط وقتی صفحه *داخل* بله باز شود در دسترس است. پس اینجا هیچ تصمیمی دربارهٔ
هویت گرفته نمی‌شود: نه شناسهٔ کاربر بله به حسابی وصل می‌شود، نه شماره یا نامی
تطبیق داده می‌شود. ربات فقط کاربر را به همان صفحهٔ حساب در وب‌اپ راهنمایی
می‌کند و مرجع نهایی، سرور است (endpointهای /api/account/identities/*).

پیش‌تر دکمهٔ «بازکردن بله» در صفحهٔ حساب به `?start=link_account` اشاره می‌کرد
ولی ربات چنین پارامتری را نمی‌شناخت و کاربر به منوی اصلی می‌رسید؛ این ماژول
همان پارامتر را واقعی می‌کند.
"""
from bale_api import send
from config import NORA_WEBAPP_URL

ACCOUNT_PAGE = "account.html"
# نشانهٔ صریح «مسیر پیوند حساب». صفحه با دیدن همین پارامتر ورود خودکار مینی‌اپ
# را کنار می‌گذارد تا امضای یک‌بارمصرف بله برای اثبات مالکیت در پیوند بماند.
LINK_MARKER = "link=bale"


def account_webapp_url(base=None):
    """نشانی صفحهٔ حساب در وب‌اپ بله؛ رشتهٔ خالی یعنی وب‌اپ تنظیم نشده است.

    پارامتر `link=bale` مسیر پیوند را برای صفحه صریح می‌کند؛ خودِ امضای بله
    هرگز در نشانی نمی‌آید و همان‌جا داخل مینی‌اپ ساخته می‌شود.
    """
    root = (NORA_WEBAPP_URL if base is None else base) or ""
    root = root.rstrip("/")
    if not root:
        return ""
    return f"{root}/{ACCOUNT_PAGE}?{LINK_MARKER}"


def start(cid, uid=None, user=None):
    """پاسخ به `?start=link_account` — باز کردن صفحهٔ حساب در بله."""
    url = account_webapp_url()
    if not url:
        return send(cid, "\n".join([
            "🔗 پیوند حساب با بله",
            "━━━━━━━━━━━━━━",
            "",
            "نشانی وب‌اپ روی این سرور تنظیم نشده، بنابراین امکان اثبات مالکیت داخل بله نیست.",
            "اگر حساب داری، از سایت با شمارهٔ موبایل وارد شو؛ پیوند از آن‌جا هم قابل پیگیری است.",
        ]))
    return send(cid, "\n".join([
        "🔗 پیوند حساب با بله",
        "━━━━━━━━━━━━━━",
        "",
        "برای وصل‌کردن این حساب بله به حسابت، صفحهٔ حساب را همین‌جا در بله باز کن؛",
        "امضای اثبات مالکیت فقط داخل بله ساخته می‌شود و ربات هیچ هویتی را خودش وصل نمی‌کند.",
        "بعد از پیوند، اعلان‌ها و فایل‌هایت در همین ربات هم به همان حساب می‌رسد.",
    ]), {"inline_keyboard": [[
        {"text": "🔗 بازکردن صفحهٔ حساب", "web_app": {"url": url}},
    ]]})
