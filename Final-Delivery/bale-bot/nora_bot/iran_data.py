def cities_of(province):
    """شهرهای یک استان"""
    return PROVINCES.get(province, [])


def find_province(name):
    """پیدا کردن استان با نام تقریبی"""
    if not name:
        return None
    n = str(name).strip()
    if n in PROVINCES:
        return n
    for p in PROVINCE_LIST:
        if p.replace("‌", "") == n.replace("‌", ""):
            return p
    return None
